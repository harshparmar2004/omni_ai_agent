const DEFAULT_GTA6_TAGS = [
  '#gta6', '#gta6leaks', '#rockstargames', '#gtavi'
];

/**
 * Clean up text generated by LLM (removes unwanted quotes, extra headers, etc.)
 */
function sanitizeLlmOutput(text) {
  if (!text) return '';
  return text
    .replace(/^["'“”]/g, '')
    .replace(/["'“”]$/g, '')
    .replace(/^(Caption|Here is the caption|Post|Instagram Caption):?\s*/gi, '')
    .replace(/#\w+/g, '') // remove any stray hashtags LLM outputted
    .trim();
}

/**
 * Calls Google Gemini REST API (gemini-1.5-flash)
 */
async function callGemini(prompt, apiKey) {
  const model = getSetting('gemini_model', 'gemini-1.5-flash');
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const res = await axios.post(
    url,
    {
      contents: [
        {
          parts: [{ text: prompt }]
        }
      ],
      generationConfig: {
        temperature: 0.4,
        maxOutputTokens: 600
      }
    },
    { timeout: 20000 }
  );

  const text = res.data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) throw new Error('Empty response from Gemini');
  return text.trim();
}

/**
 * Calls Groq REST API (llama-3.3-70b-versatile)
 */
async function callGroq(prompt, apiKey) {
  const model = getSetting('groq_model', 'llama-3.3-70b-versatile');
  const res = await axios.post(
    'https://api.groq.com/openai/v1/chat/completions',
    {
      model,
      messages: [
        {
          role: 'system',
          content: 'You are an elite, viral Instagram gaming copywriter. You write captivating, punchy, high-energy breakdowns.'
        },
        { role: 'user', content: prompt }
      ],
      temperature: 0.4,
      max_tokens: 600
    },
    {
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json'
      },
      timeout: 20000
    }
  );

  const text = res.data?.choices?.[0]?.message?.content;
  if (!text) throw new Error('Empty response from Groq');
  return text.trim();
}

/**
 * Calls local Ollama API
 */
async function callOllama(prompt) {
  const endpoint = getSetting('ollama_endpoint', 'http://localhost:11434');
  const model = getSetting('default_model', 'gemma4:e4b');

  const res = await axios.post(
    `${endpoint}/api/chat`,
    {
      model,
      messages: [
        {
          role: 'system',
          content: 'You are an elite Instagram copywriter. Write short, viral, high-energy hooks and breakdowns.'
        },
        { role: 'user', content: prompt }
      ],
      stream: false,
      options: {
        temperature: 0.4,
        num_predict: 500
      }
    },
    { timeout: 5000 }
  );

  const text = res.data?.message?.content;
  if (!text) throw new Error('Empty response from Ollama');
  return text.trim();
}

/**
 * Core AI Caption Generator
 *
 * @param {Object} options
 * @param {string} options.rawCaption - Original raw text from source reel
 * @param {string} options.sourceUsername - Competitor creator handle
 * @param {Object} options.page - Target destination page configuration
 * @returns {Promise<{ caption: string, provider: string, model: string }>}
 */
async function generateAiCaption({ rawCaption = '', sourceUsername = '', page = {} }) {
  const isClubbing = (page.slug && page.slug.includes('club')) ||
                     (page.handle && page.handle.includes('club')) ||
                     (page.name && /club|rave|party|dance|edm|techno|concert/i.test(page.name)) ||
                     page.id === 3 || String(page.id) === '3';

  const isMovie = (page.slug && page.slug.includes('movie')) ||
                  (page.handle && page.handle.includes('movie')) ||
                  (page.name && /movie|series|film|cinema/i.test(page.name)) ||
                  page.id === 2 || String(page.id) === '2';

  const isEvolvingAi = (page.slug && (page.slug === 'ai_curation' || page.slug.includes('evolving') || page.slug.includes('ai'))) ||
                       (page.handle && (page.handle.includes('evolving') || page.handle.includes('ai'))) ||
                       (page.name && /evolving|ai|tech|silicon|chips/i.test(page.name)) ||
                       page.id === 4 || String(page.id) === '4';

  const defaultHandle = isClubbing ? 'clubbingcult' : (isMovie ? 'movie_series_365' : (isEvolvingAi ? 'evolving.ai' : 'gta6_updates_007'));
  const handle = page.handle || `@${page.slug || defaultHandle}`;
  const pageName = page.name || (isClubbing ? 'Clubbing Cult' : (isMovie ? 'Movie Recommendations' : (isEvolvingAi ? 'Evolving AI' : 'GTA 6 Updates')));
  const competitorHandles = sourceUsername ? [sourceUsername] : [];
  const cleanedSource = stripHashtagsFromText(cleanRawCaption(rawCaption, competitorHandles));

  // ── Dedicated Clubbing Cult Caption Engine ──
  if (isClubbing) {
    console.log('[LLM Service] 🪩 Clubbing Cult Account detected: Generating high-energy festival/rave caption & footer.');
    const clubbingBody = cleanedSource || '🔊 TURN UP THE VOLUME! LIVE SET DROP 🔥';

    const clubbingEngagement = [
      "🔥 Rate this track/set 1-10 in the comments below! 👇",
      "💾 Save this reel & send to your party crew! 🔊"
    ].join('\n');

    const clubbingFollowLine = `🪩 Follow ${handle} for the wildest club sets, concert moments & festival drops!`;

    const originalTags = extractHashtags(rawCaption);
    const defaultTags = extractHashtags(page.default_hashtags || '#clubbing #party #houseparty #concert #rave #techno #edm #nightlife #festivals #clubbingcult');
    const nicheClubTags = ['#clubbing', '#party', '#houseparty', '#concert', '#rave', '#techno', '#edm', '#nightlife', '#festivals', '#clubbingcult'];

    const tagSet = new Set();
    const mergedTags = [];
    for (const tag of [...nicheClubTags, ...defaultTags, ...originalTags]) {
      const lower = tag.toLowerCase();
      if (!tagSet.has(lower) && tagSet.size < 6) {
        tagSet.add(lower);
        mergedTags.push(tag);
      }
    }
    const hashtagBlock = mergedTags.join(' ');

    const finalClubbingCaption = [clubbingBody, clubbingEngagement, clubbingFollowLine, hashtagBlock]
      .filter(Boolean)
      .join('\n\n')
      .trim();

    return {
      caption: finalClubbingCaption,
      provider: 'original_curated_clubbing',
      model: 'none',
      breakdown: clubbingBody
    };
  }

  // ── Dedicated Movie & Cinema Caption Engine ──
  // Preserves original scraped reel info (title, year, IMDb, synopsis, comments)
  // and cleanly appends movie engagement, follow CTA, and curated hashtags at the bottom.
  if (isMovie) {
    console.log('[LLM Service] 🍿 Movie Account detected: Preserving original reel caption & appending cinema footer.');
    const movieBody = cleanedSource || '🍿 MUST-WATCH CINEMA RECOMMENDATION 🎬';

    const movieEngagement = [
      "💬 What's your thoughts on this? Drop your reaction below 👇",
      "💾 Save this reel so you don't lose it!"
    ].join('\n');

    const movieFollowLine = `🍿 Follow ${handle} for daily movie & series recommendations!`;

    const originalTags = extractHashtags(rawCaption);
    const defaultTags = extractHashtags(page.default_hashtags || '#movies #movierecommendations #filmtok #cinema #mustwatch #365movies');
    const nicheMovieTags = ['#movies', '#movierecommendations', '#filmtok', '#cinema', '#mustwatch', '#365movies'];

    const tagSet = new Set();
    const mergedTags = [];
    for (const tag of [...nicheMovieTags, ...defaultTags, ...originalTags]) {
      const lower = tag.toLowerCase();
      if (!tagSet.has(lower) && tagSet.size < 6) {
        tagSet.add(lower);
        mergedTags.push(tag);
      }
    }
    const hashtagBlock = mergedTags.join(' ');

    const finalMovieCaption = [movieBody, movieEngagement, movieFollowLine, hashtagBlock]
      .filter(Boolean)
      .join('\n\n')
      .trim();

    return {
      caption: finalMovieCaption,
      provider: 'original_curated_movie',
      model: 'none',
      breakdown: movieBody
    };
  }

  // ── Dedicated Evolving AI Copy & Hook Engine ──
  if (isEvolvingAi) {
    console.log('[LLM Service] 🤖 Evolving AI Account detected: Generating viral hook headline & video-essay breakdown.');

    const defaultAiHeadline = 'The next generation of AI is evolving faster than anyone expected';
    let headline = defaultAiHeadline;
    let aiBreakdown = cleanedSource || 'Breakthrough development in artificial intelligence model reasoning and computing hardware.';
    let usedProvider = 'deterministic';
    let usedModel = 'none';

    // If source has sentences, extract a punchy first sentence as fallback hook
    if (cleanedSource) {
      const firstSentence = cleanedSource.split(/[.!?\n]/)[0].trim();
      if (firstSentence && firstSentence.length >= 15 && firstSentence.length <= 110) {
        headline = firstSentence.replace(/^["'“”]/, '').replace(/["'“”]$/, '');
      }
    }

    const aiPrompt = `You are the lead content creator and writer for "${pageName}" (${handle}), an elite Instagram channel producing viral high-retention video-essays.
Analyze the source description and generate two items in strict JSON format:
1. "headline": A punchy, curiosity-driven viral hook headline for the top video overlay. Must be 8 to 15 words, high-impact, attention-grabbing, with NO emojis and NO hashtags. (Example: "The most expensive AI chips in the world are now worth more than $10,000,000,000").
2. "breakdown": A high-energy 2-3 sentence video-essay post body explaining the significance, scale, or mind-blowing reality of this topic.

Source Content:
"""
${cleanedSource || 'Groundbreaking development and high-impact industry highlights.'}
"""

Respond ONLY with valid JSON in this exact structure:
{"headline": "...", "breakdown": "..."}`;

    const preferredProvider = getSetting('default_provider', 'gemini');
    const geminiKey = getSetting('gemini_api_key', '') || process.env.GEMINI_API_KEY || '';
    const groqKey = getSetting('groq_api_key', '') || process.env.GROQ_API_KEY || '';

    const providersToTry = [];
    if (preferredProvider === 'groq') {
      if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(aiPrompt, groqKey), model: 'llama-3.3-70b-versatile' });
      if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(aiPrompt, geminiKey), model: 'gemini-1.5-flash' });
    } else if (preferredProvider === 'ollama') {
      providersToTry.push({ name: 'ollama', fn: () => callOllama(aiPrompt), model: 'local' });
      if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(aiPrompt, geminiKey), model: 'gemini-1.5-flash' });
      if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(aiPrompt, groqKey), model: 'llama-3.3-70b-versatile' });
    } else {
      if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(aiPrompt, geminiKey), model: 'gemini-1.5-flash' });
      if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(aiPrompt, groqKey), model: 'llama-3.3-70b-versatile' });
    }

    for (const provider of providersToTry) {
      try {
        console.log(`[LLM Service] Querying ${provider.name} for Evolving AI copy...`);
        const rawOutput = await provider.fn();
        if (rawOutput) {
          try {
            const jsonMatch = rawOutput.match(/\{[\s\S]*\}/);
            const parsed = jsonMatch ? JSON.parse(jsonMatch[0]) : null;
            if (parsed && parsed.headline) {
              headline = parsed.headline.trim();
              if (parsed.breakdown) aiBreakdown = parsed.breakdown.trim();
              usedProvider = provider.name;
              usedModel = provider.model;
              break;
            }
          } catch (jsonErr) {
            console.warn('[LLM Service] Could not parse JSON from LLM, using fallback extraction:', jsonErr.message);
          }
        }
      } catch (err) {
        console.warn(`[LLM Service] Provider ${provider.name} failed: ${err.message}`);
      }
    }

    const aiEngagement = [
      "💬 Will this change everything, or is it overhyped? Drop your thoughts below 👇",
      "💾 Save this reel & share with someone following the AI revolution! 🚀"
    ].join('\n');

    const aiFollowLine = `🤖 Follow ${handle} for daily breakthrough AI updates & tech breakdowns!`;

    const originalTags = extractHashtags(rawCaption);
    const defaultTags = extractHashtags(page.default_hashtags || '#ai #technology #artificialintelligence #tech #future #innovation #evolvingai');
    const nicheAiTags = ['#ai', '#technology', '#artificialintelligence', '#tech', '#future', '#innovation', '#evolvingai'];

    const tagSet = new Set();
    const mergedTags = [];
    for (const tag of [...nicheAiTags, ...defaultTags, ...originalTags]) {
      const lower = tag.toLowerCase();
      if (!tagSet.has(lower) && tagSet.size < 6) {
        tagSet.add(lower);
        mergedTags.push(tag);
      }
    }
    const hashtagBlock = mergedTags.join(' ');

    const finalAiCaption = [aiBreakdown, aiEngagement, aiFollowLine, hashtagBlock]
      .filter(Boolean)
      .join('\n\n')
      .trim();

    return {
      caption: finalAiCaption,
      hookHeadline: headline,
      provider: usedProvider,
      model: usedModel,
      breakdown: aiBreakdown
    };
  }

  const prompt = `You are an elite, viral Instagram Reels copywriter managing "${pageName}" (${handle}).
Rewrite the following gaming clip description into an ultra-viral, scroll-stopping Instagram Reel caption for GTA 6 fans.

Rules for Maximum Virality:
1. PUNCHY HOOK: Start with an irresistible 1-line hook using emojis that creates intense curiosity or excitement (e.g. 🚨 WAIT UNTIL YOU SEE THIS DETAIL IN GTA 6..., 🤯 ROCKSTAR GAMES REALLY OUTDID THEMSELVES HERE..., 🔥 NEW VICE CITY LEAK CHANGES EVERYTHING...).
2. CRISP BREAKDOWN: Explain the visual, mechanics, physics, or story detail in 2 short, thrilling sentences with strong gaming keywords (Vice City, Rockstar Games, Lucia, Jason, PS5 Graphics, physics).
3. COMMENT DEBATE PROMPT: Ask a polarizing, high-engagement question that forces viewers to comment (e.g. "What do you think: Masterpiece or overhyped? Drop your thoughts below 👇", "Will this be the greatest game in history? 👇").
4. SAVE CALL-TO-ACTION: Include a quick save trigger ("💾 Save this reel so you don't lose it!").
5. DO NOT mention any credits, creator handles, or sources.
6. DO NOT include hashtags or follow CTAs (they are added automatically).
7. Length: 50-90 words maximum. Clean, high energy, no fluff.

Source Content:
"""
${cleanedSource || 'Latest game engine details, physics enhancements, and map scale highlights.'}
"""`;

  let aiBreakdown = '';
  let usedProvider = 'deterministic';
  let usedModel = 'none';

  const preferredProvider = getSetting('default_provider', 'gemini');
  const geminiKey = getSetting('gemini_api_key', '') || process.env.GEMINI_API_KEY || '';
  const groqKey = getSetting('groq_api_key', '') || process.env.GROQ_API_KEY || '';

  // Determine provider trial order
  const providersToTry = [];
  if (preferredProvider === 'groq') {
    if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(prompt, groqKey), model: 'llama-3.3-70b-versatile' });
    if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(prompt, geminiKey), model: 'gemini-1.5-flash' });
  } else if (preferredProvider === 'ollama') {
    providersToTry.push({ name: 'ollama', fn: () => callOllama(prompt), model: 'local' });
    if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(prompt, geminiKey), model: 'gemini-1.5-flash' });
    if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(prompt, groqKey), model: 'llama-3.3-70b-versatile' });
  } else {
    // Default: Gemini first, Groq second
    if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(prompt, geminiKey), model: 'gemini-1.5-flash' });
    if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(prompt, groqKey), model: 'llama-3.3-70b-versatile' });
  }

  for (const p of providersToTry) {
    try {
      console.log(`[LLM Service] 🤖 Attempting caption generation via ${p.name.toUpperCase()}...`);
      const output = await p.fn();
      if (output && output.length > 20) {
        aiBreakdown = sanitizeLlmOutput(output);
        usedProvider = p.name;
        usedModel = p.model;
        console.log(`[LLM Service] ✅ Caption generated successfully with ${p.name}!`);
        break;
      }
    } catch (err) {
      console.warn(`[LLM Service] ⚠️ ${p.name} generation failed: ${err.message}. Trying next fallback...`);
    }
  }

  // Deterministic fallback if all AI providers fail or keys not set
  if (!aiBreakdown) {
    console.log('[LLM Service] ℹ️ Using deterministic caption transformer fallback.');
    if (cleanedSource) {
      aiBreakdown = `🚨 NEW GTA 6 BREAKDOWN:\n\n${cleanedSource}\n\n💬 What are your thoughts on this? Drop your reaction below 👇\n\n💾 Save this reel so you don't lose it!`;
    } else {
      aiBreakdown = `🚨 Insane new look at GTA 6 in action! Rockstar Games is taking Vice City realism, AI mechanics, and world detail to a whole new level.\n\n💬 Will GTA 6 live up to the massive hype? Let us know below 👇\n\n💾 Save this reel so you don't lose it!`;
    }
  }

  // ── Construct Structured Components (STRICTLY NO ATTRIBUTION / CREDITS) ──
  // 1. High-converting Follow CTA line
  const followLine = `🔥 Follow ${handle} for daily ${pageName} leaks, secrets & official news!`;

  // 2. Deduplicate and collect hashtags (Strict 4-5 high-impact niche tags)
  const originalTags = extractHashtags(rawCaption);
  const defaultTags = extractHashtags(page.default_hashtags || '#gta6 #gtavi #rockstargames #vicecity #gta6leaks');
  const nicheTags = (page.slug && page.slug.includes('gta')) ? DEFAULT_GTA6_TAGS : [];

  const tagSet = new Set();
  const mergedTags = [];

  for (const tag of [...nicheTags, ...defaultTags, ...originalTags]) {
    const lower = tag.toLowerCase();
    if (!tagSet.has(lower) && tagSet.size < 5) {
      tagSet.add(lower);
      mergedTags.push(tag);
    }
  }

  const hashtagBlock = mergedTags.join(' ');

  // 3. Assemble final caption without any third-party credit
  const parts = [aiBreakdown.trim(), followLine];
  if (hashtagBlock) parts.push(hashtagBlock);

  let finalCaption = parts.join('\n\n').trim();

  // Enforce Instagram character limit (2,200 chars max)
  if (finalCaption.length > 2180) {
    const overage = finalCaption.length - 2150;
    const truncatedBreakdown = aiBreakdown.substring(0, Math.max(80, aiBreakdown.length - overage)) + '...';
    const trimmedParts = [truncatedBreakdown, followLine];
    if (hashtagBlock) trimmedParts.push(hashtagBlock);
    finalCaption = trimmedParts.join('\n\n').trim();
  }

  return {
    caption: finalCaption,
    provider: usedProvider,
    model: usedModel,
    breakdown: aiBreakdown
  };
}

