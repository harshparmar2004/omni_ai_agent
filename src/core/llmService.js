const axios = require('axios');
const { getSetting } = require('../database');
const { cleanRawCaption, extractHashtags, stripHashtagsFromText } = require('./captionBuilder');

/**
 * OmniStudio v7 — LLM Copywriting & Viral Caption Service
 * Generates high-energy, buffed captions for Instagram Reels with:
 * 1. Hook & Topic Breakdown
 * 2. Competitor Shout-out: 🙌 Shout-out & thanks to @source for this resource!
 * 3. Page Follow CTA: 🔔 Follow @page for the latest updates every hour!
 * 4. Deduplicated Viral Hashtags
 */

const DEFAULT_GTA6_TAGS = [
  '#gta6', '#gtavi', '#rockstargames', '#grandtheftauto',
  '#vicecity', '#gta6trailer', '#gta6leaks', '#gaming',
  '#gamers', '#playstation5', '#ps5', '#xboxseriesx',
  '#videogames', '#gtaonline', '#gamingcommunity'
];

/**
 * Clean up text generated by LLM (removes unwanted quotes, extra headers, etc.)
 */
function sanitizeLlmOutput(text) {
  if (!text) return '';
  return text
    .replace(/^["'“”]/g, '')
    .replace(/["'“”]$/g, '')
    .replace(/^(Caption|Here is the caption|Post|Instagram Caption):?\s*/gi, '')
    .replace(/#\w+/g, '') // remove any stray hashtags LLM outputted
    .trim();
}

/**
 * Calls Google Gemini REST API (gemini-1.5-flash)
 */
async function callGemini(prompt, apiKey) {
  const model = getSetting('gemini_model', 'gemini-1.5-flash');
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const res = await axios.post(
    url,
    {
      contents: [
        {
          parts: [{ text: prompt }]
        }
      ],
      generationConfig: {
        temperature: 0.4,
        maxOutputTokens: 600
      }
    },
    { timeout: 20000 }
  );

  const text = res.data?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) throw new Error('Empty response from Gemini');
  return text.trim();
}

/**
 * Calls Groq REST API (llama-3.3-70b-versatile)
 */
async function callGroq(prompt, apiKey) {
  const model = getSetting('groq_model', 'llama-3.3-70b-versatile');
  const res = await axios.post(
    'https://api.groq.com/openai/v1/chat/completions',
    {
      model,
      messages: [
        {
          role: 'system',
          content: 'You are an elite, viral Instagram gaming copywriter. You write captivating, punchy, high-energy breakdowns.'
        },
        { role: 'user', content: prompt }
      ],
      temperature: 0.4,
      max_tokens: 600
    },
    {
      headers: {
        Authorization: `Bearer ${apiKey}`,
        'Content-Type': 'application/json'
      },
      timeout: 20000
    }
  );

  const text = res.data?.choices?.[0]?.message?.content;
  if (!text) throw new Error('Empty response from Groq');
  return text.trim();
}

/**
 * Calls local Ollama API
 */
async function callOllama(prompt) {
  const endpoint = getSetting('ollama_endpoint', 'http://localhost:11434');
  const model = getSetting('default_model', 'gemma4:e4b');

  const res = await axios.post(
    `${endpoint}/api/chat`,
    {
      model,
      messages: [
        {
          role: 'system',
          content: 'You are an elite Instagram copywriter. Write short, viral, high-energy hooks and breakdowns.'
        },
        { role: 'user', content: prompt }
      ],
      stream: false,
      options: {
        temperature: 0.4,
        num_predict: 500
      }
    },
    { timeout: 5000 }
  );

  const text = res.data?.message?.content;
  if (!text) throw new Error('Empty response from Ollama');
  return text.trim();
}

/**
 * Core AI Caption Generator
 *
 * @param {Object} options
 * @param {string} options.rawCaption - Original raw text from source reel
 * @param {string} options.sourceUsername - Competitor creator handle
 * @param {Object} options.page - Target destination page configuration
 * @returns {Promise<{ caption: string, provider: string, model: string }>}
 */
async function generateAiCaption({ rawCaption = '', sourceUsername = '', page = {} }) {
  const pageName = page.name || 'GTA 6 Updates';
  const handle = page.handle || `@${page.slug || 'gta6_updates_007'}`;
  const competitorHandles = sourceUsername ? [sourceUsername] : [];
  const cleanedSource = stripHashtagsFromText(cleanRawCaption(rawCaption, competitorHandles));

  const prompt = `You are the lead content creator and hype copywriter for an Instagram page dedicated to "${pageName}".
Analyze the following source reel description and rewrite it into an exciting, high-energy, viral breakdown for our followers:

Rules:
1. Start with an irresistible, punchy 1-2 line hook with emojis (e.g. 🚨 BREAKING: ..., 🔥 NEW DETAILS REVEALED: ..., 🤯 LOOK AT THIS: ...).
2. Buff and expand the breakdown: explain the feature, leak, mechanic, or storyline clearly in 2 to 4 engaging bullet points or short punchy paragraphs.
3. Make it feel authoritative, immersive, and thrilling for fans.
4. DO NOT write any shout-out or follow CTA lines (these are automatically appended).
5. DO NOT include hashtags (these are automatically appended).
6. DO NOT include fake URLs, links in bio, or spam comments.
7. Length: 60-120 words maximum.

Source Content:
"""
${cleanedSource || 'Latest game engine details, physics enhancements, and map scale highlights.'}
"""`;

  let aiBreakdown = '';
  let usedProvider = 'deterministic';
  let usedModel = 'none';

  const preferredProvider = getSetting('default_provider', 'gemini');
  const geminiKey = getSetting('gemini_api_key', '') || process.env.GEMINI_API_KEY || '';
  const groqKey = getSetting('groq_api_key', '') || process.env.GROQ_API_KEY || '';

  // Determine provider trial order
  const providersToTry = [];
  if (preferredProvider === 'groq') {
    if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(prompt, groqKey), model: 'llama-3.3-70b-versatile' });
    if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(prompt, geminiKey), model: 'gemini-1.5-flash' });
  } else if (preferredProvider === 'ollama') {
    providersToTry.push({ name: 'ollama', fn: () => callOllama(prompt), model: 'local' });
    if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(prompt, geminiKey), model: 'gemini-1.5-flash' });
    if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(prompt, groqKey), model: 'llama-3.3-70b-versatile' });
  } else {
    // Default: Gemini first, Groq second
    if (geminiKey) providersToTry.push({ name: 'gemini', fn: () => callGemini(prompt, geminiKey), model: 'gemini-1.5-flash' });
    if (groqKey) providersToTry.push({ name: 'groq', fn: () => callGroq(prompt, groqKey), model: 'llama-3.3-70b-versatile' });
  }

  for (const p of providersToTry) {
    try {
      console.log(`[LLM Service] 🤖 Attempting caption generation via ${p.name.toUpperCase()}...`);
      const output = await p.fn();
      if (output && output.length > 20) {
        aiBreakdown = sanitizeLlmOutput(output);
        usedProvider = p.name;
        usedModel = p.model;
        console.log(`[LLM Service] ✅ Caption generated successfully with ${p.name}!`);
        break;
      }
    } catch (err) {
      console.warn(`[LLM Service] ⚠️ ${p.name} generation failed: ${err.message}. Trying next fallback...`);
    }
  }

  // Deterministic fallback if all AI providers fail or keys not set
  if (!aiBreakdown) {
    console.log('[LLM Service] ℹ️ Using deterministic caption transformer fallback.');
    if (cleanedSource) {
      aiBreakdown = `🔥 LATEST UPDATE:\n\n${cleanedSource}`;
    } else {
      aiBreakdown = `🔥 Exclusive look at the latest ${pageName} breakdown! The graphics, mechanics, and realism are taking this to an unprecedented level.`;
    }
  }

  // ── Construct Structured Components ──────────────────────
  // 1. Shout-out line
  let shoutoutLine = '';
  if (page.attribution_enabled !== 0 && sourceUsername && sourceUsername.toLowerCase() !== 'instagram' && !sourceUsername.toLowerCase().includes(page.slug || 'none')) {
    shoutoutLine = `🙌 Shout-out & thanks to @${sourceUsername} for this resource!`;
  }

  // 2. Hourly Follow CTA line
  const followLine = `🔔 Follow ${handle} for the latest ${pageName} updates every hour!`;

  // 3. Deduplicate and collect hashtags
  const originalTags = extractHashtags(rawCaption);
  const defaultTags = extractHashtags(page.default_hashtags || '');
  const nicheTags = (page.slug && page.slug.includes('gta')) ? DEFAULT_GTA6_TAGS : [];

  const tagSet = new Set();
  const mergedTags = [];

  for (const tag of [...defaultTags, ...nicheTags, ...originalTags]) {
    const lower = tag.toLowerCase();
    if (!tagSet.has(lower) && tagSet.size < 25) {
      tagSet.add(lower);
      mergedTags.push(tag);
    }
  }

  const hashtagBlock = mergedTags.join(' ');

  // 4. Assemble final caption
  const parts = [aiBreakdown.trim()];
  if (shoutoutLine) parts.push(shoutoutLine);
  if (followLine) parts.push(followLine);
  if (hashtagBlock) parts.push(hashtagBlock);

  let finalCaption = parts.join('\n\n').trim();

  // Enforce Instagram character limit (2,200 chars max)
  if (finalCaption.length > 2180) {
    const overage = finalCaption.length - 2150;
    const truncatedBreakdown = aiBreakdown.substring(0, Math.max(80, aiBreakdown.length - overage)) + '...';
    const trimmedParts = [truncatedBreakdown];
    if (shoutoutLine) trimmedParts.push(shoutoutLine);
    if (followLine) trimmedParts.push(followLine);
    if (hashtagBlock) trimmedParts.push(hashtagBlock);
    finalCaption = trimmedParts.join('\n\n').trim();
  }

  return {
    caption: finalCaption,
    provider: usedProvider,
    model: usedModel,
    breakdown: aiBreakdown
  };
}

